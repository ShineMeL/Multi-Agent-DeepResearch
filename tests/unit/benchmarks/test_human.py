from __future__ import annotations

import json
from typing import Literal

import pytest
from pydantic import ValidationError

from benchmarks.evaluators.human import (
    HUMAN_DIMENSIONS,
    HumanRating,
    ReportPair,
    blind_pair,
    summarize_human_ratings,
    validate_human_ratings,
)


def _pair() -> ReportPair:
    return ReportPair(
        task_id="stability-01",
        left_run_id="run-a-001",
        right_run_id="run-d-001",
        left_variant="variant_a",
        right_variant="variant_d",
        left_model="model-a",
        right_model="model-d",
        left_cost_usd=0.12,
        right_cost_usd=0.18,
        left_tokens=123,
        right_tokens=456,
        left_latency_ms=100.0,
        right_latency_ms=150.0,
        left_report="Report generated by variant_a using model-a.",
        right_report="Report generated by variant_d using model-d.",
    )


def _rating(
    task_id: str,
    rater_id: str,
    *,
    preference: Literal["X", "Y", "TIE"] = "X",
) -> HumanRating:
    return HumanRating(
        packet_id=f"packet-{task_id}",
        task_id=task_id,
        rater_id=rater_id,
        report_label="X",
        scores={dimension: 4 for dimension in HUMAN_DIMENSIONS},
        overall_preference=preference,
        rationale="The reports are clear and sufficiently supported.",
    )


def test_blinding_removes_variant_and_run_identifiers() -> None:
    pair = _pair()
    packet = blind_pair(pair, seed=20260829)
    payload = packet.model_dump_json()
    assert "variant_a" not in payload.casefold()
    assert "variant_d" not in payload.casefold()
    assert pair.left_run_id not in payload
    assert pair.right_run_id not in payload
    assert "model-a" not in payload.casefold()
    assert "model-d" not in payload.casefold()
    assert "cost_usd" not in payload
    assert "tokens" not in payload
    assert "latency_ms" not in payload
    assert {packet.report_x, packet.report_y} == {
        "Report generated by [REDACTED] using [REDACTED]."
    }


def test_blinding_is_seeded_but_does_not_expose_mapping() -> None:
    pair = _pair()
    first = blind_pair(pair, seed=7)
    second = blind_pair(pair, seed=7)
    assert first == second
    assert first.packet_id == second.packet_id
    assert first.model_dump() == {
        "packet_id": first.packet_id,
        "task_id": "stability-01",
        "report_x": first.report_x,
        "report_y": first.report_y,
    }


def test_human_rating_schema_rejects_unknown_dimensions_and_bad_scores() -> None:
    with pytest.raises(ValidationError):
        HumanRating(
            packet_id="packet-1",
            task_id="task-1",
            rater_id="rater-1",
            report_label="X",
            scores={"unknown": 4},
            overall_preference="TIE",
            rationale="No rationale.",
        )
    with pytest.raises(ValidationError):
        HumanRating(
            packet_id="packet-1",
            task_id="task-1",
            rater_id="rater-1",
            report_label="X",
            scores={HUMAN_DIMENSIONS[0]: 6},
            overall_preference="TIE",
            rationale="No rationale.",
        )


def test_every_task_requires_three_distinct_raters() -> None:
    ratings = [_rating("task-1", f"rater-{index}") for index in range(1, 4)]
    report = validate_human_ratings(ratings, expected_tasks=1, raters_per_task=3)
    assert report.valid
    assert report.raters_per_task == {"task-1": 3}

    duplicate = ratings[:-1] + [ratings[0].model_copy(update={"rater_id": "rater-1"})]
    invalid = validate_human_ratings(duplicate, expected_tasks=1, raters_per_task=3)
    assert not invalid.valid
    assert any("distinct" in error for error in invalid.errors)


def test_human_summary_reports_agreement_and_spearman() -> None:
    ratings = [
        _rating("task-1", "rater-1", preference="X"),
        _rating("task-1", "rater-2", preference="X"),
        _rating("task-1", "rater-3", preference="Y"),
        _rating("task-2", "rater-1", preference="Y"),
        _rating("task-2", "rater-2", preference="Y"),
        _rating("task-2", "rater-3", preference="Y"),
    ]
    result = summarize_human_ratings(
        ratings,
        automatic_metrics={
            "task-1": {"completeness": 0.4, "citation_support": 0.2},
            "task-2": {"completeness": 0.8, "citation_support": 0.7},
        },
    )
    assert set(result.krippendorff_alpha) == set(HUMAN_DIMENSIONS)
    assert set(result.auto_metric_spearman) == set(HUMAN_DIMENSIONS)
    assert set(result.auto_metric_spearman[HUMAN_DIMENSIONS[0]]) == {
        "completeness",
        "citation_support",
    }
    assert result.majority_preference == {"X": 1, "Y": 1, "TIE": 0}
    assert result.tie_rate == 0.0
    assert abs(result.mean_dimension_scores[HUMAN_DIMENSIONS[0]] - 4.0) < 1e-9  # type: ignore[operator]


def test_summary_preserves_missingness_and_requires_three_raters() -> None:
    ratings = [_rating("task-1", f"rater-{index}") for index in range(1, 3)]
    report = validate_human_ratings(ratings, expected_tasks=1, raters_per_task=3)
    assert not report.valid
    with pytest.raises(ValueError, match="three"):
        summarize_human_ratings(ratings)


def test_rating_json_contains_no_private_blind_mapping() -> None:
    rating = _rating("task-1", "rater-1")
    payload = json.loads(rating.model_dump_json())
    assert set(payload) == {
        "packet_id",
        "task_id",
        "rater_id",
        "report_label",
        "scores",
        "overall_preference",
        "rationale",
    }
